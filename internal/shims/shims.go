package shims

import (
	"bytes"
	"fmt"
	"os/exec"
	"regexp"
	"strings"

	"github.com/arihantsethia/clipport/internal/registry"
)

const Version = "v0.1.0"

func Install(target, token string, port int) error {
	if target == "" {
		return fmt.Errorf("target is required")
	}
	if len(token) > 4096 || !validToken.MatchString(token) {
		return fmt.Errorf("token must contain 1–4096 URL-safe characters")
	}
	if port == 0 {
		port = 18765
	}
	if port < 1 || port > 65535 {
		return fmt.Errorf("port must be between 1 and 65535")
	}
	payload := renderInstallPayload(token, port)
	cmd := sshShCommand(target)
	cmd.Stdin = strings.NewReader(payload)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("install shims on %s failed: %w: %s", target, err, strings.ReplaceAll(strings.TrimSpace(string(out)), token, "[redacted]"))
	}
	_ = markShim(target)
	return nil
}

func Uninstall(target string, removeToken bool) error {
	if target == "" {
		return fmt.Errorf("target is required")
	}
	payload := renderUninstallPayload(removeToken)
	cmd := sshShCommand(target)
	cmd.Stdin = strings.NewReader(payload)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("uninstall shims on %s failed: %w: %s", target, err, strings.TrimSpace(string(out)))
	}
	return nil
}

func sshShCommand(target string) *exec.Cmd {
	return exec.Command("ssh", "-o", "PermitLocalCommand=no", "-o", "ClearAllForwardings=yes", target, "sh")
}

// Tokens generated by Clipport use the URL-safe base64 alphabet. Restricting the
// payload input also prevents delimiter/shell injection from damaged local files.
var validToken = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func renderInstallPayload(token string, port int) string {
	var b bytes.Buffer
	b.WriteString(`set -eu
umask 077
fail() { echo "clipport: $1" >&2; exit 1; }
for dir in "$HOME/.config" "$HOME/.config/clipport" "$HOME/.local" "$HOME/.local/bin"; do
  [ ! -L "$dir" ] || fail "refusing symlink installation directory"
  if [ -e "$dir" ]; then [ -d "$dir" ] || fail "invalid installation directory"; fi
done
mkdir -p "$HOME/.config/clipport" "$HOME/.local/bin"
state="$HOME/.config/clipport"
lock="$state/.shim-install.lock"
# Cooperating installs serialize before reading or writing the remote identity.
# Never break an existing lock: its owner may still be installing.
attempt=0
until mkdir "$lock" 2>/dev/null; do
  attempt=$((attempt + 1))
  [ "$attempt" -lt 5 ] || fail "remote shim setup is busy; retry after the current setup finishes (a stale .shim-install.lock requires manual inspection)"
  sleep 1
done
shim_tmp=""
cleanup() { [ -z "$shim_tmp" ] || rm -f "$shim_tmp"; rm -f "$lock/token"; rmdir "$lock"; }
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
`)
	fmt.Fprintf(&b, "printf '%%s\\n' '%s' > \"$lock/token\"\n", token)
	b.WriteString(`token_path="$state/token"
[ ! -L "$token_path" ] || fail "refusing symlink remote token"
if [ -e "$token_path" ]; then
  [ -f "$token_path" ] && [ -r "$token_path" ] || fail "remote token is not a readable regular file"
  # Byte comparison rejects empty, multiline, and otherwise malformed files too.
  cmp -s "$lock/token" "$token_path" || fail "remote token differs or is malformed; this remote account may belong to another Clipport client. Existing token and shims were left unchanged"
fi
shim="$HOME/.local/bin/clipport-wl-paste"
[ ! -L "$shim" ] || fail "refusing symlink shim file"
if [ -e "$shim" ]; then [ -f "$shim" ] && [ -r "$shim" ] || fail "shim is not a readable regular file"; fi
for name in wl-paste xclip; do
  link="$HOME/.local/bin/$name"
  if [ -L "$link" ]; then
    [ "$(readlink "$link")" = "$shim" ] || fail "refusing to replace an unrelated clipboard command"
  elif [ -e "$link" ]; then
    fail "refusing to replace an unrelated clipboard command"
  fi
done
# Hard-link publication cannot overwrite a token, even if it appeared after the check.
if [ ! -e "$token_path" ]; then
  ln "$lock/token" "$token_path" || fail "remote token appeared during setup; retry after inspecting it"
fi
chmod 600 "$token_path"
shim_tmp=$(mktemp "$HOME/.local/bin/.clipport-shim.XXXXXX")
cat > "$shim_tmp" <<'CLIPPORT_SHIM'
`)
	fmt.Fprintf(&b, "%sCLIPPORT_SHIM\n", renderScript(port))
	b.WriteString(`chmod 755 "$shim_tmp"
mv -f "$shim_tmp" "$shim"
shim_tmp=""
for name in wl-paste xclip; do
  link="$HOME/.local/bin/$name"
  if [ ! -L "$link" ]; then ln -s "$shim" "$link"; fi
done
`)
	return b.String()
}

func renderUninstallPayload(removeToken bool) string {
	var b bytes.Buffer
	fmt.Fprintf(&b, "set -eu\n")
	fmt.Fprintf(&b, "shim=\"$HOME/.local/bin/clipport-wl-paste\"\n")
	fmt.Fprintf(&b, "for name in wl-paste xclip; do\n")
	fmt.Fprintf(&b, "  link=\"$HOME/.local/bin/$name\"\n")
	fmt.Fprintf(&b, "  if [ -L \"$link\" ]; then\n")
	fmt.Fprintf(&b, "    target=$(readlink \"$link\" || true)\n")
	fmt.Fprintf(&b, "    case \"$target\" in\n")
	fmt.Fprintf(&b, "      \"$shim\"|\"$HOME/.local/bin/clipport-wl-paste\"|~/.local/bin/clipport-wl-paste) rm -f \"$link\" ;;\n")
	fmt.Fprintf(&b, "    esac\n")
	fmt.Fprintf(&b, "  fi\n")
	fmt.Fprintf(&b, "done\n")
	fmt.Fprintf(&b, "rm -f \"$shim\"\n")
	if removeToken {
		fmt.Fprintf(&b, "rm -f \"$HOME/.config/clipport/token\"\n")
	}
	return b.String()
}

func renderScript(port int) string {
	var b bytes.Buffer
	fmt.Fprintf(&b, "#!/bin/sh\n")
	fmt.Fprintf(&b, "set -eu\n")
	fmt.Fprintf(&b, "CLIPPORT_PORT=${CLIPPORT_PORT:-%d}\n", port)
	fmt.Fprintf(&b, "CLIPPORT_TOKEN=${CLIPPORT_TOKEN:-$(cat \"$HOME/.config/clipport/token\" 2>/dev/null || true)}\n")
	fmt.Fprintf(&b, "url=\"http://127.0.0.1:${CLIPPORT_PORT}/v1/clipboard\"\n")
	fmt.Fprintf(&b, "curl_stderr=/dev/null\n")
	fmt.Fprintf(&b, "if [ \"${CLIPPORT_DEBUG:-}\" = \"1\" ]; then curl_stderr=/dev/stderr; fi\n")
	fmt.Fprintf(&b, "if [ -n \"$CLIPPORT_TOKEN\" ] && command -v curl >/dev/null 2>&1 && curl -fsS -H \"Authorization: Bearer ${CLIPPORT_TOKEN}\" \"$url\" 2>\"$curl_stderr\"; then exit 0; fi\n")
	fmt.Fprintf(&b, "name=$(basename \"$0\")\n")
	fmt.Fprintf(&b, "PATH_WITHOUT_SHIMS=$(printf '%%s' \"$PATH\" | awk -v RS=: -v ORS=: '$0 != ENVIRON[\"HOME\"] \"/.local/bin\" {print}' | sed 's/:$//')\n")
	fmt.Fprintf(&b, "real=$(PATH=\"$PATH_WITHOUT_SHIMS\" command -v \"$name\" 2>/dev/null || true)\n")
	fmt.Fprintf(&b, "if [ -n \"$real\" ]; then exec \"$real\" \"$@\"; fi\n")
	fmt.Fprintf(&b, "echo \"clipport: clipboard tunnel unavailable and no fallback $name found\" >&2\n")
	fmt.Fprintf(&b, "exit 127\n")
	return b.String()
}

func markShim(target string) error {
	reg, err := registry.Load("")
	if err != nil {
		return err
	}
	reg.UpdateHost(target, func(st registry.HostState) registry.HostState {
		st.ShimVersion = Version
		return st
	})
	return reg.Save("")
}
